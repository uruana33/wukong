#!/usr/bin/env python3
"""动作配置表校验与生成：策划的 actions.json -> src/combat 可用的 TS 数据表片段

输入 JSON 形如：
[
  {"actionId": 1, "name": "LIGHT_1", "state": "ATTACK", "totalFrames": 24,
   "hitboxActive": [7, 11],
   "hit": {"damage": 8, "hitLevel": "LIGHT", "poiseDamage": 15,
           "knockbackForce": 4, "hitStunFrames": 12},
   "cancelWindows": [{"triggerInput": "LIGHT_ATTACK", "targetActionId": 2,
                      "window": [14, 20], "requireHit": true}]}
]

校验规则（不符合即报错退出，不把脏数据放进代码）：
  - hitboxActive / cancelWindows.window 必须落在 [0, totalFrames] 内
  - perfectWindow 必须嵌套在 iFrames 前段（[i0, x] 且 x <= i1）
  - cancelWindows.targetActionId 必须存在于表内
"""
import json
import sys
from pathlib import Path


def validate(actions: list[dict]) -> list[str]:
    errors = []
    ids = {a.get("actionId") for a in actions}
    for a in actions:
        name = a.get("name", a.get("actionId"))
        total = a.get("totalFrames", 0)

        def check_window(w, label):
            if not (isinstance(w, list) and len(w) == 2 and 0 <= w[0] <= w[1] <= total):
                errors.append(f"{name}: {label} {w} 越界 [0, {total}]")

        if "hitboxActive" in a:
            check_window(a["hitboxActive"], "hitboxActive")
        for cw in a.get("cancelWindows", []):
            check_window(cw["window"], f"cancelWindow->{cw['targetActionId']}")
            if cw["targetActionId"] not in ids:
                errors.append(f"{name}: 取消目标 {cw['targetActionId']} 不在表内")
        if "iFrames" in a:
            check_window(a["iFrames"], "iFrames")
            pw = a.get("perfectWindow")
            if pw:
                check_window(pw, "perfectWindow")
                if not (pw[0] >= a["iFrames"][0] and pw[1] <= a["iFrames"][1]):
                    errors.append(f"{name}: perfectWindow {pw} 未嵌套在 iFrames {a['iFrames']} 内")
    return errors


def emit_ts(actions: list[dict]) -> str:
    """生成可粘贴进 src/combat/data.ts 的 ACTIONS 片段"""
    lines = ["// === generated by tools/config_generator.py, do not edit by hand ==="]
    for a in actions:
        lines.append(f"    {a['actionId']}: {json.dumps(a, ensure_ascii=False)},")
    return "\n".join(lines)


if __name__ == "__main__":
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "actions.json")
    actions = json.loads(src.read_text())
    errors = validate(actions)
    if errors:
        for e in errors:
            print(f"[ERROR] {e}", file=sys.stderr)
        sys.exit(1)
    print(emit_ts(actions))
